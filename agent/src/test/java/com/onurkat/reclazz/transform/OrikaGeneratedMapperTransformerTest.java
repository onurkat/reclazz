package com.onurkat.reclazz.transform;

import com.onurkat.reclazz.bootstrap.DispatchTable;
import com.onurkat.reclazz.bootstrap.InjectedNames;
import org.junit.jupiter.api.Test;
import java.lang.invoke.MethodHandles;
import java.lang.reflect.InvocationTargetException;
import java.util.Map;
import static org.junit.jupiter.api.Assertions.*;

class OrikaGeneratedMapperTransformerTest extends TransformTestBase {
    private static final String CALLER = "ma/glasnost/orika/generated/ExampleMapper";

    @Test void generatedCallerUsesAddedAccessorOnExistingClassAcrossRetargets() throws Exception {
        var classes = compile(
                new SourceFile("com.example.Dto", "package com.example; public class Dto { public String getAdded(){return null;} }"),
                new SourceFile(CALLER.replace('/', '.'), """
                    package ma.glasnost.orika.generated;
                    public class ExampleMapper {
                        public static String read(com.example.Dto dto) { return dto.getAdded(); }
                    }
                    """));
        byte[] caller = classes.get(CALLER);
        classes.put("com/example/Dto", compile(new SourceFile("com.example.Dto",
                "package com.example; public class Dto { }")).get("com/example/Dto"));
        var context = new TransformContext();
        context.addWatched("com/example/Dto");
        byte[] transformed = new OrikaGeneratedMapperTransformer(context)
                .transform(getClass().getClassLoader(), CALLER, null, null, caller);
        assertNotNull(transformed);
        classes.put(CALLER, transformed);
        var loader = sharedLoader(classes);
        Class<?> owner = loader.load("com.example.Dto"), mapper = loader.load(CALLER.replace('/', '.'));
        Object receiver = owner.getConstructor().newInstance();
        var read = mapper.getMethod("read", owner);
        String key = InjectedNames.siteKey("getAdded", InjectedNames.descHash("()Ljava/lang/String;"));
        for (String value : new String[]{"first", "second"}) {
            var handle = MethodHandles.dropArguments(MethodHandles.constant(String.class, value), 0, owner);
            DispatchTable.retargetAll(owner, MethodHandles.privateLookupIn(owner, MethodHandles.lookup()), Map.of(key, handle));
            assertEquals(value, read.invoke(null, receiver));
            assertThrows(NoSuchMethodException.class, () -> owner.getDeclaredMethod("getAdded"));
        }
        // The unchanged generated bytes must fail against the same original class.
        classes.put(CALLER, caller);
        var control = sharedLoader(classes);
        Class<?> original = control.load("com.example.Dto");
        var failure = assertThrows(InvocationTargetException.class, () -> control.load(CALLER.replace('/', '.'))
                .getMethod("read", original).invoke(null, original.getConstructor().newInstance()));
        assertInstanceOf(NoSuchMethodError.class, failure.getCause());
    }

    @Test void unrelatedGeneratedAndApplicationClassesAreNotSelected() {
        var transformer = new OrikaGeneratedMapperTransformer(new TransformContext());
        for (String name : new String[]{null, "com/example/Mapper", "ma/glasnost/orika/impl/MapperFacadeImpl"})
            assertNull(transformer.transform(getClass().getClassLoader(), name, null, null, new byte[0]));
    }
}
