package com.onurkat.reclazz.plugin.hybris

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Files
import java.nio.file.Path
import kotlin.test.*

class HybrisInstallerCompositionTest {
    @TempDir lateinit var root: Path
    private val begin = "# >>> reclazz (auto-generated by Reclazz plugin, do not edit between markers)"
    private val end = "# <<< reclazz"
    private val agent = HybrisAgentInstaller.agentArgument("/synthetic tools/reclazz-agent.jar=autoSolrReindex=true")

    private fun layout(optional: Boolean): Pair<Path, Path> {
        val platform = Files.createDirectories(root.resolve("bin/platform"))
        val config = Files.createDirectories(root.resolve("config"))
        Files.writeString(platform.resolve("project.properties"), "tomcat.javaoptions=-Xmx1g\ntomcat.debugjavaoptions=-Xdebug -Xrunjdwp:transport=dt_socket,server=y\n")
        Files.writeString(config.resolve("local.properties"), if (optional) "hybris.optional.config.dir=\${HYBRIS_CONFIG_DIR}/dev/props\n" else "# preserve this\n")
        return platform to config
    }

    private fun install(platform: Path, config: Path, value: String = agent) {
        val result = HybrisAgentInstaller.installConfiguration(platform, config, value)
        assertTrue(result is HybrisAgentInstaller.Result.Success, result.toString())
    }

    @Test fun localPropertiesFallbackVerifiesOwnAddition() {
        val (platform, config) = layout(false)
        install(platform, config)
        val target = config.resolve("local.properties")
        assertEquals("-Xmx1g $agent", HybrisPropertyFiles.readProperty(target, "tomcat.javaoptions"))
        assertEquals("-Xdebug -Xrunjdwp:transport=dt_socket,server=y $agent", HybrisPropertyFiles.readProperty(target, "tomcat.debugjavaoptions"))
        assertNull(HybrisAgentInstaller.verifyOnlyAgentAdded(platform, config, agent))
        val once = Files.readString(target)
        install(platform, config)
        assertEquals(once, Files.readString(target), "Reinstall must not accumulate agents or lose the original comment")
    }

    @Test fun reinstallRegeneratesManagedBlockFromSettings() {
        val (platform, config) = layout(true)
        install(platform, config)
        val target = HybrisPropertyFiles.targetFile(config)
        Files.writeString(target, Files.readString(target).replace("autoSolrReindex=true", "autoSolrReindex=true,fromFuture=1"))
        val next = HybrisAgentInstaller.agentArgument("/synthetic tools/reclazz-agent.jar=structuralReload=false")
        install(platform, config, next)
        assertEquals("-Xmx1g $next", HybrisPropertyFiles.readProperty(target, "tomcat.javaoptions"))
        assertFalse(Files.readString(target).contains("fromFuture="), "Manual edits inside the owned block are regenerated")
        val lower = config.resolve("dev/props/10-local.properties")
        Files.writeString(lower, "tomcat.javaoptions=-Xmx2g -Dkeep=yes\n")
        install(platform, config, next)
        assertEquals("-Xmx2g -Dkeep=yes $next", HybrisPropertyFiles.readProperty(target, "tomcat.javaoptions"))
    }

    @Test fun existingAgentInLowerLayerRefusesBeforeWrite() {
        val (platform, config) = layout(true)
        val props = Files.createDirectories(config.resolve("dev/props"))
        val lower = props.resolve("10-local.properties")
        for (option in listOf("-javaagent:/tools/reclazz-agent.jar=verbose=true",
            "-javaagent:\"/tools with spaces/reclazz-agent-1.2.0.jar=verbose=true\"",
            "\"-javaagent:/tools with spaces/reclazz-agent.jar=verbose=true\"",
            "-javaagent:C:\\tools\\reclazz-agent-1.2.0-all.jar")) {
            Files.writeString(lower, "# synthetic\ntomcat.debugjavaoptions=-Xdebug $option\n")
            val before = Files.readString(lower)
            val result = HybrisAgentInstaller.installConfiguration(platform, config, agent)
            assertTrue(result is HybrisAgentInstaller.Result.Error, result.toString())
            assertContains(result.message, "$lower:2")
            assertEquals(before, Files.readString(lower))
            assertFalse(Files.exists(props.resolve("95-local.properties")))
        }
    }

    @Test fun unrelatedAgentsAndOptionValuesSurviveWhileOutsideOwnedBlockIsChecked() {
        val (platform, config) = layout(true)
        val props = Files.createDirectories(config.resolve("dev/props"))
        val lower = props.resolve("10-local.properties")
        val options = "-javaagent:\"/coverage tools/jacoco.jar=destfile=a b\" -Dnote=-javaagent:/reclazz-agent.jar -javaagent:/other.jar=path=/reclazz-agent.jar"
        Files.writeString(lower, "tomcat.javaoptions=$options\n")
        install(platform, config)
        val target = props.resolve("95-local.properties")
        assertEquals("$options $agent", HybrisPropertyFiles.readProperty(target, "tomcat.javaoptions"))
        // User options outside our block in the same target are part of the base too.
        Files.writeString(target, "tomcat.javaoptions=-Xmx3g\n" + Files.readString(target))
        install(platform, config)
        assertEquals("-Xmx3g $agent", HybrisPropertyFiles.readProperty(target, "tomcat.javaoptions"))
        Files.writeString(target, Files.readString(target) + "tomcat.debugjavaoptions=-javaagent:/reclazz-agent.jar\n")
        val before = Files.readString(target)
        assertTrue(HybrisAgentInstaller.installConfiguration(platform, config, agent) is HybrisAgentInstaller.Result.Error)
        assertEquals(before, Files.readString(target))
    }

    @Test fun rollbackRestoresPreviousManagedBlock() {
        val (platform, config) = layout(false)
        install(platform, config)
        val target = config.resolve("local.properties")
        val before = Files.readString(target)
        val next = "-javaagent:/new/reclazz-agent.jar=verbose=true"
        val result = HybrisAgentInstaller.installConfiguration(platform, config, next) { "simulated concurrent base drift" }
        assertTrue(result is HybrisAgentInstaller.Result.Error)
        assertEquals(before, Files.readString(target))
        val thrown = HybrisAgentInstaller.installConfiguration(platform, config, next) { error("verification unavailable") }
        assertTrue(thrown is HybrisAgentInstaller.Result.Error)
        assertEquals(before, Files.readString(target))
    }

    @Test fun actualBaseDriftRejectsWriteAndRestoresOnlyManagedFile() {
        val (platform, config) = layout(true)
        install(platform, config)
        val target = HybrisPropertyFiles.targetFile(config)
        val before = Files.readString(target)
        val lower = config.resolve("dev/props/10-local.properties")
        val result = HybrisAgentInstaller.installConfiguration(platform, config, agent) {
            Files.writeString(lower, "tomcat.javaoptions=-Xmx4g\n")
            HybrisAgentInstaller.verifyOnlyAgentAdded(platform, config, agent)
        }
        assertTrue(result is HybrisAgentInstaller.Result.Error)
        assertContains(result.message, "changed underneath")
        assertEquals(before, Files.readString(target))
        assertEquals("tomcat.javaoptions=-Xmx4g\n", Files.readString(lower))
    }

    @Test fun laterPropertyLayerCannotSilentlyOverrideInstalledAgent() {
        val (platform, config) = layout(true)
        val props = Files.createDirectories(config.resolve("dev/props"))
        val later = props.resolve("99-local.properties")
        val original = "tomcat.javaoptions=-Xmx8g\n"
        Files.writeString(later, original)
        val result = HybrisAgentInstaller.installConfiguration(platform, config, agent)
        assertTrue(result is HybrisAgentInstaller.Result.Error)
        assertContains(result.message, "overridden by another properties layer")
        assertEquals(original, Files.readString(later))
        assertFalse(Files.exists(props.resolve("95-local.properties")))
    }

    @Test fun failedFirstInstallRemovesOnlyNewFileAndMalformedBlockIsNotWritten() {
        val (platform, config) = layout(true)
        val target = HybrisPropertyFiles.targetFile(config)
        assertTrue(HybrisAgentInstaller.installConfiguration(platform, config, agent) { "failure" } is HybrisAgentInstaller.Result.Error)
        assertFalse(Files.exists(target))
        Files.writeString(target, "$begin\ntomcat.javaoptions=-Xmx1g\n")
        val before = Files.readString(target)
        assertTrue(HybrisAgentInstaller.installConfiguration(platform, config, agent) is HybrisAgentInstaller.Result.Error)
        assertEquals(before, Files.readString(target))
    }
}
