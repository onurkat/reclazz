        layout(javac=false);for(key in listOf("tomcat.javaoptions","tomcat.debugjavaoptions"))editOptions(key) { it.replace("autoCompile=false","autoCompile=true") }
        wrappers();assertEquals(SetupCheck.Level.FAIL,row("jdk").level)
    }
    @Test fun legacyManualAgentPathIsRecognized() {
        layout(false);val old=jar;jar=root.resolve(".reclazz/agent.jar");Files.createDirectories(jar.parent);Files.copy(old,jar)
        for(key in listOf("tomcat.javaoptions","tomcat.debugjavaoptions"))editOptions(key) { it.replace(old.toString(),jar.toString()) }
        wrappers();assertEquals(SetupCheck.Level.WARN,row("agent-line").level);assertEquals(SetupCheck.Level.OK,row("other-agents").level);assertEquals(SetupCheck.Level.OK,row("agent-jar").level)
    }
    @Test fun externalDirBasedExtensionIsKnown() {
        layout();val extension=Files.createDirectories(root.resolve("external/exampleoutside"))
        Files.writeString(config.resolve("localextensions.xml"),"<hybrisconfig><extensions><extension dir=\"$extension\"/></extensions></hybrisconfig>")
        assertEquals(SetupCheck.Level.OK,check(names=setOf("exampleoutside")).single { it.id=="extensions" }.level)
    }
    @Test fun groupedSymlinkExtensionMetadataIsDiscovered() {
        layout();val extension=Files.createDirectories(root.resolve("linked/group/deprecated/actual"));Files.writeString(extension.resolve("extensioninfo.xml"),"<extensioninfo><extension name=\"discoveredexample\"/></extensioninfo>")
        Files.createDirectories(root.resolve("bin/custom"));Files.createSymbolicLink(root.resolve("bin/custom/group"),root.resolve("linked/group"))
        assertEquals(SetupCheck.Level.OK,check(names=setOf("discoveredexample")).single { it.id=="extensions" }.level)
    }

