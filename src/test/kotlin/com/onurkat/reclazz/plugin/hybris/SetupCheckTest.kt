    @Test fun unknownJdkSkipsRatherThanGuessing() { layout();Files.delete(jdk.resolve("release"));assertEquals(SetupCheck.Level.SKIP,row("jdk").level) }
    @Test fun jrebelIsAConflict() { layout();editOptions("tomcat.javaoptions") { "$it -javaagent:/synthetic/jrebel.jar" };assertEquals(SetupCheck.Level.FAIL,row("other-agents").level) }
