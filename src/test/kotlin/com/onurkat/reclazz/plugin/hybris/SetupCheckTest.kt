class SetupCheckTest {
    @TempDir lateinit var root: Path
    private val version = "9.8.7"
    private val begin = "# >>> reclazz (auto-generated by Reclazz plugin, do not edit between markers)"
    private val end = "# <<< reclazz"
    private val debug = "-Xdebug -agentlib:jdwp=transport=dt_socket,server=y,suspend=n,address=8000"
    private lateinit var platform: Path
    private lateinit var config: Path
    private lateinit var jar: Path
    private lateinit var jdk: Path
    private fun layout(managed: Boolean = true, feature: Int = 21, javac: Boolean = true) {
        platform = Files.createDirectories(root.resolve("bin/platform"))
        config = Files.createDirectories(root.resolve("config"))
        jar = root.resolve("tools with spaces/reclazz-agent.jar"); writeJar(version)
        jdk = Files.createDirectories(root.resolve("jdk/bin")).parent
        Files.writeString(jdk.resolve("release"), "JAVA_VERSION=\"$feature.0.1\"\n")
        Files.writeString(jdk.resolve("bin/java"), "synthetic")
        if (javac) Files.writeString(jdk.resolve("bin/javac"), "synthetic")
        Files.writeString(platform.resolve("project.properties"), "tomcat.javaoptions=-Xmx1g\ntomcat.debugjavaoptions=$debug\n")
        Files.writeString(config.resolve("local.properties"), "# synthetic\n")
        if (managed) assertIs<HybrisAgentInstaller.Result.Success>(HybrisAgentInstaller.installConfiguration(platform, config, agent()))
        else Files.writeString(config.resolve("local.properties"), "tomcat.javaoptions=${agent()}\ntomcat.debugjavaoptions=$debug ${agent()}\n")
        wrappers()
        Files.writeString(config.resolve("localextensions.xml"), "<hybrisconfig><extensions><extension name=\"example\"/></extensions></hybrisconfig>")
    }
    @Test fun removedManagedAgentMakesSetupDueAgain() {
        layout()
        val app = com.onurkat.reclazz.plugin.settings.ReclazzAppState.State()
        val project = com.onurkat.reclazz.plugin.settings.ReclazzSettings.State(enabled = true)
        fun offer(): Boolean {
            val facts = com.onurkat.reclazz.plugin.setup.SetupFacts(true, version, root, check())
            val installed = com.onurkat.reclazz.plugin.setup.SetupFlow.evaluate(facts).first().status.finished
            return com.onurkat.reclazz.plugin.setup.SetupOffer.decide(app, project, version, "install", installed).dialog
        }
        assertTrue(offer())
        assertFalse(offer())
        val properties = HybrisPropertyFiles.targetFile(config)
        Files.writeString(properties, "# removed managed agent")
        assertTrue(offer())
    }
    private fun agent() = HybrisAgentInstaller.agentArgument("$jar=autoCompile=false")
    private fun writeJar(value: String?) {
        Files.createDirectories(jar.parent)
        val manifest = Manifest().apply { mainAttributes[Attributes.Name.MANIFEST_VERSION] = "1.0"; if (value != null) mainAttributes[Attributes.Name.IMPLEMENTATION_VERSION] = value }
        JarOutputStream(Files.newOutputStream(jar), manifest).use { }
    }
    private fun wrappers() {
        val dir = Files.createDirectories(platform.resolve("tomcat/conf"))
        for ((file, key) in listOf("wrapper.conf" to "tomcat.javaoptions", "wrapper-debug.conf" to "tomcat.debugjavaoptions")) {
            Files.writeString(dir.resolve(file), "wrapper.java.command=${jdk.resolve("bin/java")}\nwrapper.java.additional.1=${listOf("tomcat.generaloptions",key,"ltw.configuration").joinToString(" ") { HybrisPropertyFiles.effectiveValue(platform,config,it,false) }}\n")
        }
    }
    private fun check(autoCompile: Boolean = false, names: Set<String> = setOf("example"), server: () -> SetupCheck.Server? = { null }) =
        SetupCheck.check(SetupCheck.Input(root, version, names, autoCompile), server)
    private fun row(id: String, autoCompile: Boolean = false) = check(autoCompile).single { it.id == id }
    private fun editOptions(key: String, change: (String) -> String) {
        val path = HybrisPropertyFiles.optionalConfigDir(config, false)?.resolve(HybrisPropertyFiles.RECLAZZ_PROPERTIES) ?: config.resolve("local.properties")
        val text = Files.readString(path)
        Files.writeString(path, text.lineSequence().joinToString("\n") { if (it.startsWith("$key=")) "$key=${change(it.substringAfter('='))}" else it })
    }
    @Test fun correctManagedInstallHasEightOrderedChecks() {
        layout();val rows=check()
        assertEquals(listOf("agent-line","ant-server","debug-flags","agent-jar","jdk","other-agents","extensions","server"),rows.map { it.id })
        assertTrue(rows.dropLast(1).all { it.level == SetupCheck.Level.OK },rows.toString())
        assertEquals(SetupCheck.Level.SKIP,rows.last().level)
    }
    @Test fun validManualAgentWarnsWithoutOtherAgentFailure() { layout(false);assertEquals(SetupCheck.Level.WARN,row("agent-line").level);assertEquals(SetupCheck.Level.OK,row("other-agents").level);assertTrue(check().none { it.level==SetupCheck.Level.FAIL }) }
    @Test fun missingAgentFails() { layout();editOptions("tomcat.javaoptions") { "-Xmx1g" };assertEquals(SetupCheck.Level.FAIL,row("agent-line").level) }
    @Test fun duplicateAgentFails() { layout();editOptions("tomcat.javaoptions") { "$it ${agent()}" };assertEquals(SetupCheck.Level.FAIL,row("agent-line").level) }
    @Test fun missingJarFails() { layout();Files.delete(jar);assertEquals(SetupCheck.Level.FAIL,row("agent-jar").level) }
    @Test fun olderJarWarns() { layout();writeJar("1.0.0");assertEquals(SetupCheck.Level.WARN,row("agent-jar").level) }
    @Test fun jarWithoutVersionDoesNotClaimMatch() { layout();writeJar(null);assertEquals(SetupCheck.Level.WARN,row("agent-jar").level) }
    @Test fun unreadableJarFails() { layout();Files.writeString(jar,"not a jar");assertEquals(SetupCheck.Level.FAIL,row("agent-jar").level) }
    @Test fun lostDebugFlagsFail() { layout();editOptions("tomcat.debugjavaoptions") { agent() };assertEquals(SetupCheck.Level.FAIL,row("debug-flags").level) }
    @Test fun userBaseDebugFlagEditMustNotBeSilentlyOverridden() {
        layout();val path=config.resolve("local.properties");val text=Files.readString(path)
