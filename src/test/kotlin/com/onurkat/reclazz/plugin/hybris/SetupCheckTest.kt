    private fun manualResolvedPath(raw:String) {
        layout(managed=false);val actual=root.resolve("bin/reclazz-agent.jar");Files.copy(jar,actual)
        Files.writeString(config.resolve("local.properties"),"tomcat.javaoptions=-javaagent:$raw\ntomcat.debugjavaoptions=$debug -javaagent:$raw\n");wrappers()
        for(name in listOf("wrapper.conf","wrapper-debug.conf")){val p=platform.resolve("tomcat/conf/$name");Files.writeString(p,Files.readString(p).replace(raw,actual.toString()))}
        assertEquals(SetupCheck.Level.OK,row("agent-jar").level);assertEquals(SetupCheck.Level.OK,row("ant-server").level)
    }
