    @Test fun unrelatedJavaAgentWarns() { layout();editOptions("tomcat.javaoptions") { "$it -javaagent:/synthetic/jacoco.jar=destfile=/synthetic/coverage" };assertEquals(SetupCheck.Level.WARN,row("other-agents").level) }
    @Test fun nativeAgentWarns() { layout();editOptions("tomcat.javaoptions") { "$it -agentpath:/synthetic/libmonitor.dylib" };assertEquals(SetupCheck.Level.WARN,row("other-agents").level) }
    @Test fun optionValueContainingAgentTextIsNotAnAgent() { layout();editOptions("tomcat.javaoptions") { "$it -Dexample=-javaagent:/synthetic/jrebel.jar" };assertEquals(SetupCheck.Level.OK,row("other-agents").level) }
    @Test fun unknownExtensionWarns() { layout();val finding=check(names=setOf("example","missing")).single { it.id=="extensions" };assertEquals(SetupCheck.Level.WARN,finding.level);assertContains(finding.message,"missing") }
    @Test fun optionalConfigWinningLayerIsChecked() {
        layout();val optional=Files.createDirectories(config.resolve("optional"));Files.writeString(config.resolve("local.properties"),"hybris.optional.config.dir=\${HYBRIS_CONFIG_DIR}/optional\n")
        Files.writeString(optional.resolve("95-local.properties"),"$begin\ntomcat.javaoptions=${agent()}\ntomcat.debugjavaoptions=$debug ${agent()}\n$end\n");wrappers()
        assertEquals(SetupCheck.Level.OK,row("agent-line").level);assertEquals(SetupCheck.Level.OK,row("ant-server").level)
    }
    @Test fun missingOptionalDirectoryStaysMissingAndFilesStayUnchanged() {
        layout();val absent=config.resolve("never-create");val p=config.resolve("local.properties");Files.writeString(p,Files.readString(p)+"\nhybris.optional.config.dir=\${HYBRIS_CONFIG_DIR}/never-create\n")
        val before=Files.walk(root).use { paths -> paths.filter(Files::isRegularFile).toList().associateWith { Files.readAllBytes(it).toList() } }
        check();assertFalse(Files.exists(absent));val after=Files.walk(root).use { paths -> paths.filter(Files::isRegularFile).toList().associateWith { Files.readAllBytes(it).toList() } };assertEquals(before,after)
    }
