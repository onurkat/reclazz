    @Test fun staleNormalWrapperFailsWithAntServerFix() { layout();val p=platform.resolve("tomcat/conf/wrapper.conf");Files.writeString(p,Files.readString(p).replace("autoCompile=false","autoCompile=true"));val finding=row("ant-server");assertEquals(SetupCheck.Level.FAIL,finding.level);assertContains(finding.fix,"ant server") }
    @Test fun staleDebugWrapperFails() { layout();val p=platform.resolve("tomcat/conf/wrapper-debug.conf");Files.writeString(p,Files.readString(p).replace("address=8000","address=9000"));assertEquals(SetupCheck.Level.FAIL,row("ant-server").level) }
    @Test fun newerUnrelatedPropertyDoesNotInvalidateEffectiveWrapper() { layout();val p=config.resolve("local.properties");Files.writeString(p,Files.readString(p)+"\nunrelated.setting=true\n");Files.setLastModifiedTime(p,FileTime.fromMillis(System.currentTimeMillis()+100000));assertEquals(SetupCheck.Level.OK,row("ant-server").level) }
    @Test fun quotedAndWhitespaceEquivalentOptionsAreAccepted() { layout();val p=platform.resolve("tomcat/conf/wrapper.conf");Files.writeString(p,Files.readString(p).replace("-Xmx1g ","-Xmx1g    "));assertEquals(SetupCheck.Level.OK,row("ant-server").level) }
